def normalize_program_name(value):
    return re.sub(r'[^a-zа-яё0-9]+', ' ', str(value or '').casefold()).strip()


@lru_cache(maxsize=1)
def _priority_index():
    return {
        normalize_program_name(name): {
            'code': code,
            'degree': degree,
            'name': name,
            'service_fee_usd': price,
            'is_priority': True,
        }
        for code, degree, name, price in PRIORITY_PROGRAMS
    }


def priority_offer_for_name(value):
    normalized = normalize_program_name(value)
    if not normalized:
        return None
    exact = _priority_index().get(normalized)
    if exact:
        return exact
    candidates = [
        (name, offer)
        for name, offer in _priority_index().items()
        if len(name) >= 5 and (name in normalized or normalized in name)
    ]
    return max(candidates, key=lambda item: len(item[0]))[1] if candidates else None
